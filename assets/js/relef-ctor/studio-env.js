// Студийное окружение для зеркального серебра. RoomEnvironment (штатная
// комната three) даёт РОВНЫЙ светлый купол — металл в нём выходит сатиновым:
// бликов много, но они размазаны. Полированному металлу нужны немногие
// ДЛИННЫЕ яркие софтбоксы на тёмном фоне — тогда шинка ведёт непрерывную
// световую полосу, а грани рельефа вспыхивают контрастно («реально
// отполированный», Арбак 20.08). Значения цветов > 1 намеренно: PMREM
// читает сцену как HDR, и пересвет софтбокса и есть сила блика.
import * as THREE from './three.js';

export function studioEnv() {
  const scene = new THREE.Scene();
  // Купол СВЕТЛЫЙ: зеркальный металл целиком принимает цвет окружения, и
  // чёрная студия делает из серебра чёрный хром (первый заход, поймано).
  // Серебро = светло-серое поле + немногие яркие полосы + пара тёмных
  // акцентов для графитовых рёбер.
  scene.background = new THREE.Color().setScalar(0.45);

  const box = (w, h, intensity, pos, lookAt = [0, 0, 0]) => {
    const m = new THREE.Mesh(
      new THREE.PlaneGeometry(w, h),
      new THREE.MeshBasicMaterial({ color: new THREE.Color().setScalar(intensity) }),
    );
    m.position.set(...pos);
    m.lookAt(...lookAt);
    scene.add(m);
  };

  // Стены разной яркости: однотонный купол заливал рельеф плоским молоком
  // (второй заход) — переливы между гранями рождаются только там, где
  // соседние направления отражают РАЗНЫЙ тон.
  box(20, 12, 0.62, [0, 2, -9]);     // задняя, самая светлая — фон лица монеты
  box(20, 12, 0.38, [0, 2, 9]);      // передняя темнее
  box(18, 12, 0.50, [-9, 2, 0]);     // левая
  box(18, 12, 0.30, [9, 2, 0]);      // правая, самая тёмная
  // Потолок ПОЛОСАМИ, не плитой: лицо монеты смотрит вверх, и сплошной
  // потолок заливал рельеф ровным молоком (третий заход). Чередование
  // яркостей над головой — это и есть переливы на склонах и площадке.
  box(20, 2.4, 0.85, [0, 8, -5.2]);
  box(20, 1.8, 0.22, [0, 8, -2.6]);
  box(20, 2.6, 3.0, [0, 8, 0.2]);
  box(20, 1.6, 0.30, [0, 8, 2.8]);
  box(20, 2.4, 1.2, [0, 8, 5.2]);

  // пол чуть темнее купола — низ шинки мягко темнеет, как на белом столе
  const floor = new THREE.Mesh(new THREE.PlaneGeometry(24, 24),
    new THREE.MeshBasicMaterial({ color: new THREE.Color().setScalar(0.24) }));
  floor.rotation.x = -Math.PI / 2; floor.position.y = -3;
  scene.add(floor);

  // ключевой верхний софтбокс: длинная полоса чуть спереди — главный блик,
  // который шинка носит по всей дуге
  box(7, 2.6, 7, [0, 5, 2.5]);
  // ОКНО с переплётом слева: четыре ярких стекла на тёмной раме. Отражение
  // окна — то, что делает металл «живущим в комнате», а не в боксе
  // («видно окно, что-то ещё» — Арбак 20.08 о правильном референсе).
  box(4.2, 5.4, 0.10, [-6, 2.2, -1]);            // рама-подложка
  const pane = (dy, dz) => box(1.75, 2.35, 6, [-5.9, 2.2 + dy, -1 + dz], [0, 1.2, 0]);
  pane(1.35, -1.05); pane(1.35, 1.05); pane(-1.35, -1.05); pane(-1.35, 1.05);
  // правый контровой: узкий и злой — режущая кромка на рёбрах рельефа
  box(1.0, 6, 9, [4.6, 2, -2.2]);
  // нижняя передняя планка поднимает низ шинки
  box(5, 0.7, 2.2, [0, -2.2, 4.6]);
  // «предметы в комнате»: тёмные вертикальные силуэты и тёплая столешница —
  // графитовые рёбра на полировке и едва тёплый отсвет снизу
  box(1.2, 6, 0.06, [-2.8, 1.5, 4.2]);
  box(1.6, 5, 0.14, [4.2, 0.5, 3.6]);
  box(6, 1.0, 0.10, [2.5, -0.6, -4.8]);
  const warm = new THREE.Mesh(new THREE.PlaneGeometry(7, 2),
    new THREE.MeshBasicMaterial({ color: new THREE.Color(0.55, 0.47, 0.36) }));
  warm.position.set(2, -2.4, 2.8); warm.lookAt(0, 0, 0);
  scene.add(warm);

  return scene;
}
